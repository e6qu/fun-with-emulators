#!/usr/bin/env python3
"""Generate Linux arm64 ABI tables (syscall numbers, errno) for crates/abi.

Usage: tools/gen-abi.py [INCLUDE_DIR]

INCLUDE_DIR defaults to /usr/include and must contain the Linux UAPI headers
(asm-generic/unistd.h, asm-generic/errno-base.h, asm-generic/errno.h).
arm64 uses the asm-generic syscall table with the configuration below.
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "abi" / "src" / "generated.rs"

# arch/arm64/include/uapi/asm/unistd.h configuration.
# Table bookkeeping macros, not system calls.
NOT_SYSCALLS = {"__NR_syscalls", "__NR_arch_specific_syscall"}

ARM64_DEFINES = [
    "__ARCH_WANT_RENAMEAT",
    "__ARCH_WANT_NEW_STAT",
    "__ARCH_WANT_SET_GET_RLIMIT",
    "__ARCH_WANT_SYS_CLONE3",
    "__ARCH_WANT_MEMFD_SECRET",
]


def macros(include_dir: str, header: str, defines: list[str]) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as shim, tempfile.NamedTemporaryFile("w", suffix=".c") as src:
        # Stand-in for arch/arm64/include/uapi/asm: only the word size matters.
        (Path(shim) / "asm").mkdir()
        (Path(shim) / "asm" / "bitsperlong.h").write_text(
            "#define __BITS_PER_LONG 64\n#include <asm-generic/bitsperlong.h>\n"
        )
        src.write(f"#include <{header}>\n")
        src.flush()
        cmd = ["cc", "-E", "-dM", "-nostdinc", "-I", shim, "-I", include_dir]
        cmd += [f"-D{d}" for d in defines]
        cmd.append(src.name)
        out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    result = {}
    for line in out.splitlines():
        m = re.match(r"#define (\w+) (.+)$", line)
        if m:
            result[m.group(1)] = m.group(2).strip()
    return result


def resolve(defs: dict[str, str], name: str, depth: int = 0) -> int | None:
    value = defs.get(name)
    if value is None or depth > 16:
        return None
    value = value.strip("()")
    if re.fullmatch(r"\d+", value):
        return int(value)
    if re.fullmatch(r"\w+", value):
        return resolve(defs, value, depth + 1)
    return None


def main() -> None:
    include_dir = sys.argv[1] if len(sys.argv) > 1 else "/usr/include"

    sys_defs = macros(include_dir, "asm-generic/unistd.h", ARM64_DEFINES)
    syscalls = {}
    for name in sys_defs:
        if not name.startswith("__NR_") or name in NOT_SYSCALLS:
            continue
        number = resolve(sys_defs, name)
        if number is not None:
            syscalls[number] = name[len("__NR_"):]
    max_nr = resolve(sys_defs, "__NR_syscalls")

    err_defs = macros(include_dir, "asm-generic/errno.h", [])
    # Primary names are the ones defined with a literal; the rest are aliases
    # (EWOULDBLOCK = EAGAIN, EDEADLOCK = EDEADLK).
    errnos = {}
    for name, value in err_defs.items():
        if re.fullmatch(r"E[A-Z0-9]+", name) and re.fullmatch(r"\d+", value):
            errnos[int(value)] = name
    aliases = {
        name: resolve(err_defs, name)
        for name in err_defs
        if re.fullmatch(r"E[A-Z0-9]+", name)
        and resolve(err_defs, name) is not None
        and errnos[resolve(err_defs, name)] != name
    }

    lines = [
        "// @generated by tools/gen-abi.py from the Linux UAPI headers. Do not edit.",
        "",
        "/// Linux arm64 system call numbers.",
        "pub mod nr {",
    ]
    for number in sorted(syscalls):
        lines.append(f"    pub const {syscalls[number].upper()}: u64 = {number};")
    lines += [
        "}",
        "",
        f"/// One past the highest system call number in the table.",
        f"pub const SYSCALL_COUNT: u64 = {max_nr};",
        "",
        "/// Name of a Linux arm64 system call, if known.",
        "pub fn syscall_name(nr: u64) -> Option<&'static str> {",
        "    Some(match nr {",
    ]
    for number in sorted(syscalls):
        lines.append(f'        {number} => "{syscalls[number]}",')
    lines += [
        "        _ => return None,",
        "    })",
        "}",
        "",
        "/// Linux errno values.",
        "pub mod errno {",
    ]
    for number in sorted(errnos):
        lines.append(f"    pub const {errnos[number]}: i32 = {number};")
    for name in sorted(aliases):
        lines.append(f"    pub const {name}: i32 = {aliases[name]};")
    lines += [
        "}",
        "",
        "/// Symbolic name of a Linux errno value, if known.",
        "pub fn errno_name(errno: i32) -> Option<&'static str> {",
        "    Some(match errno {",
    ]
    for number in sorted(errnos):
        lines.append(f'        {number} => "{errnos[number]}",')
    lines += [
        "        _ => return None,",
        "    })",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(syscalls)} syscalls, {len(errnos)} errnos")


if __name__ == "__main__":
    main()
